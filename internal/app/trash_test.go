package app

import "testing"

func TestTrashListsRestorableRecordsAcrossRestart(t *testing.T) {
	e := setup(t)
	c := e.client()
	c.signIn()
	payment := c.createPayment(nil)
	base := "/api/v1/recurring-payments/" + id(payment)
	period := c.get("/api/v1/payment-occurrences").list(t)[0]
	periodPath := base + "/periods/" + period["due_date"].(string)
	occurrencePath := "/api/v1/payment-occurrences/" + id(period)
	expect(t, "paid", c.patch(occurrencePath, map[string]any{"paid": true, "paid_at": "2026-01-27"}).status, 200)
	expect(t, "attach", c.upload(occurrencePath+"/receipts", "check.png", pngBytes).status, 201)
	expect(t, "remove period", c.delete(periodPath).status, 204)
	items := c.get("/api/v1/deleted-payments").list(t)
	expect(t, "one item", len(items), 1)
	expect(t, "period", items[0]["kind"], any("period"))
	expect(t, "paid date", items[0]["paid_at"], any("2026-01-27"))
	expect(t, "period title", items[0]["title"], payment["title"])
	expect(t, "archive", c.delete(base).status, 204)
	expect(t, "remove parent", c.delete(base+"?mode=delete").status, 204)
	e.http.Close()
	e.db.Close()
	e.start()
	c = e.client()
	c.signIn()
	items = c.get("/api/v1/deleted-payments").list(t)
	expect(t, "no double-count of removed child", len(items), 1)
	expect(t, "parent after restart", items[0]["kind"], any("payment"))
	expect(t, "archived preserved", items[0]["active"], any(false))
	expect(t, "parent date absent", items[0]["due_date"], nil)
	expect(t, "restore parent", c.post(base+"/restore", nil).status, 204)
	items = c.get("/api/v1/deleted-payments").list(t)
	expect(t, "separately removed child still recoverable", len(items), 1)
	expect(t, "child", items[0]["kind"], any("period"))
	expect(t, "restore child", c.post(periodPath+"/restore", nil).status, 204)
	expect(t, "empty trash", len(c.get("/api/v1/deleted-payments").list(t)), 0)
	restored := c.get(occurrencePath).object(t)
	expect(t, "receipt retained", restored["receipts"], any(1.0))
	expect(t, "date retained", restored["paid_at"], any("2026-01-27"))
	expect(t, "archive retained", restored["active"], any(false))
	expect(t, "audit intact", c.get("/api/v1/audit-log/verify").object(t)["ok"], any(true))
}

func TestTrashRequiresAdministrator(t *testing.T) {
	e := setup(t)
	c := e.client()
	expect(t, "anonymous", c.get("/api/v1/deleted-payments").status, 401)
	expect(t, "page requires sign-in", c.get("/trash").status, 303)
	c.signIn()
	expect(t, "restore page is served", c.get("/trash").status, 200)
	c.post("/api/v1/users", map[string]any{"email": "trash@example.com", "username": "reader", "display_name": "Reader", "password": "User-password123!"})
	user := e.client()
	user.signIn("reader", "User-password123!")
	expect(t, "ordinary user", user.get("/api/v1/deleted-payments").status, 403)
	expect(t, "admin empty array", len(c.get("/api/v1/deleted-payments").list(t)), 0)
}
