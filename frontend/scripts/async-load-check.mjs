import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import vm from 'node:vm';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const swc = require('next/dist/build/swc');
await swc.loadBindings();
const source = readFileSync(new URL('../lib/async-load.ts', import.meta.url), 'utf8');
const { code } = await swc.transform(source, { filename: 'async-load.ts', jsc: { parser: { syntax: 'typescript' }, target: 'es2022' }, module: { type: 'commonjs' } });
const exports = {}; vm.runInNewContext(code, { exports, Error, Promise });
const { createLatestLoader } = exports;
const pending = []; const values = []; const errors = [];
const loader = createLatestLoader(() => new Promise((resolve, reject) => pending.push({ resolve, reject })), (v) => values.push(v), (e) => errors.push(e.message));
const flush = () => new Promise((r) => setImmediate(r));
void loader.request();
for (let i = 0; i < 100; i++) void loader.request();
assert.equal(pending.length, 1, 'burst must not start parallel requests');
pending[0].resolve('first'); await flush();
assert.deepEqual(values, ['first'], 'in-flight result must not be starved by live events');
assert.equal(pending.length, 2, 'all events coalesce into one follow-up');
pending[1].reject(new Error('network')); await flush();
assert.deepEqual(errors, ['network']);
void loader.request(); assert.equal(pending.length, 3, 'failed requests can recover');
loader.dispose(); pending[2].resolve('old filters'); await flush();
assert.deepEqual(values, ['first'], 'disposed query must not overwrite current filters');
void loader.request(); assert.equal(pending.length, 3);
console.log('async loading: coalescing, no starvation, retries and stale-query protection pass');
